WITH filtered_forecasts AS (
  SELECT
    FACILITY_ID,
    FORECAST_VERSION_START_DATE,
    PRODUCTION_DATETIME,
    COALESCE(PLAN_LIQUID_GES_PERCENTAGE, 0) AS LIQUID_GES_PERCENTAGE,
    COALESCE(PLAN_GAS_GES_PERCENTAGE, 0) AS GAS_GES_PERCENTAGE,
    PLAN_OIL_PRODUCTION_VOLUME_BBL,
    PLAN_GAS_PRODUCTION_VOLUME_BEQ,
    PLAN_GAS_FLARE_VOLUME_BEQ,
    PLAN_GAS_FUEL_VOLUME_BEQ,
    PLAN_GAS_VENT_VOLUME_BEQ,
    PLAN_OIL_SCHEDULED_DEFERRED_VOLUME_BBL,
    PLAN_GAS_SCHEDULED_DEFERRED_VOLUME_BEQ,
    PLAN_OIL_UNSCHEDULED_DEFERRED_VOLUME_BBL,
    PLAN_GAS_UNSCHEDULED_DEFERRED_VOLUME_BEQ
  FROM hive_metastore.dm_prod.vw_fact_asset_production_forecast_temporal
  WHERE BUSINESS_DOMAIN_CODE = 'BD0036'
    AND FORECAST_TYPE_CODE = 'BP'
    AND FORECAST_SCENARIO_NAME = 'Technical'
    AND FORECAST_VERSION_START_DATE >= DATE '2019-01-01'
    AND PRODUCTION_DATETIME < DATE '2027-01-01'
)

SELECT
  FH.BUSINESS_AREA_NAME,
  FH.FACILITY_06_SHORT_NAME,
  CONCAT('OP', YEAR(F.FORECAST_VERSION_START_DATE) - 2001) AS Forecast,
  date_trunc('MONTH', F.PRODUCTION_DATETIME) AS `Prod Date`,
  SUM(
    COALESCE(F.PLAN_OIL_PRODUCTION_VOLUME_BBL, 0) * F.LIQUID_GES_PERCENTAGE / 100
    + (
        COALESCE(F.PLAN_GAS_PRODUCTION_VOLUME_BEQ, 0)
        - COALESCE(F.PLAN_GAS_FLARE_VOLUME_BEQ, 0)
        - COALESCE(F.PLAN_GAS_FUEL_VOLUME_BEQ, 0)
        - COALESCE(F.PLAN_GAS_VENT_VOLUME_BEQ, 0)
      ) * F.GAS_GES_PERCENTAGE / 100
  ) AS AFS,
  SUM(
    COALESCE(F.PLAN_OIL_SCHEDULED_DEFERRED_VOLUME_BBL, 0)
      * F.LIQUID_GES_PERCENTAGE / 100
    + COALESCE(F.PLAN_GAS_SCHEDULED_DEFERRED_VOLUME_BEQ, 0)
      * F.GAS_GES_PERCENTAGE / 100
  ) AS SCH_DEF,
  SUM(
    COALESCE(F.PLAN_OIL_UNSCHEDULED_DEFERRED_VOLUME_BBL, 0)
      * F.LIQUID_GES_PERCENTAGE / 100
    + COALESCE(F.PLAN_GAS_UNSCHEDULED_DEFERRED_VOLUME_BEQ, 0)
      * F.GAS_GES_PERCENTAGE / 100
  ) AS UNSCH_DEF
FROM filtered_forecasts AS F
INNER JOIN hive_metastore.dm_mdm.dim_facility_hierarchy AS FH
  ON FH.FACILITY_ID = F.FACILITY_ID
WHERE FH.ASSET_DOMAIN_NAME <> 'DW Prod GoM Historic'
GROUP BY
  FH.BUSINESS_AREA_NAME,
  FH.FACILITY_06_SHORT_NAME,
  CONCAT('OP', YEAR(F.FORECAST_VERSION_START_DATE) - 2001),
  date_trunc('MONTH', F.PRODUCTION_DATETIME)