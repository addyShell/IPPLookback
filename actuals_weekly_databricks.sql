WITH facility_hierarchy AS (
  SELECT
    FACILITY_ID,
    BUSINESS_AREA_NAME,
    FACILITY_06_SHORT_NAME
  FROM hive_metastore.dm_mdm.dim_facility_hierarchy
  WHERE BUSINESS_DOMAIN_NAME = 'UPG Gulf of America'
    AND ASSET_DOMAIN_NAME <> 'DW Prod GoA Historic'
),
weekly_actuals AS (
  SELECT
    FH.BUSINESS_AREA_NAME,
    FH.FACILITY_06_SHORT_NAME,
    'Actuals' AS Forecast,
    date_sub(next_day(SN_ACTUALS.PRODUCTION_DATETIME, 'MON'), 7) AS PRODUCTION_DATETIME,
    SUM(
      COALESCE(SN_ALLOCATED_HC_LIQUID_PRODUCTION_VOLUME_BBL, 0)
        + COALESCE(SN_ALLOCATED_GAS_WELLHEAD_PRODUCTION_VOLUME_BEQ, 0)
        - COALESCE(SN_ALLOCATED_GAS_FUEL_VOLUME_BEQ, 0)
        - COALESCE(SN_ALLOCATED_GAS_FLARE_VOLUME_BEQ, 0)
        - COALESCE(SN_ALLOCATED_GAS_VENT_VOLUME_BEQ, 0)
    ) AS AFS,
    SUM(
      COALESCE(SN_ACTUALS.SN_ALLOCATED_HC_LIQUID_UNSCHEDULED_DEFERRED_VOLUME_BBL, 0)
        + COALESCE(SN_ACTUALS.SN_ALLOCATED_GAS_UNSCHEDULED_DEFERRED_VOLUME_BEQ, 0)
    ) AS UNSCH_DEF,
    SUM(
      COALESCE(SN_ACTUALS.SN_ALLOCATED_HC_LIQUID_SCHEDULED_DEFERRED_VOLUME_BBL, 0)
        + COALESCE(SN_ACTUALS.SN_ALLOCATED_GAS_SCHEDULED_DEFERRED_VOLUME_BEQ, 0)
    ) AS SCH_DEF
  FROM facility_hierarchy AS FH
  JOIN hive_metastore.dm_prod.vw_fact_facility_shell_net_production_daily AS SN_ACTUALS
    ON SN_ACTUALS.FACILITY_ID = FH.FACILITY_ID
  WHERE SN_ACTUALS.PRODUCTION_DATETIME >= DATE '2026-01-01'
  GROUP BY
    FH.BUSINESS_AREA_NAME,
    FH.FACILITY_06_SHORT_NAME,
    date_sub(next_day(SN_ACTUALS.PRODUCTION_DATETIME, 'MON'), 7)
)
SELECT *
FROM weekly_actuals
