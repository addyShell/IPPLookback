WITH filtered_forecasts AS (
  SELECT
    F.*,
    date_sub(next_day(F.PRODUCTION_DATETIME, 'MON'), 7) AS WEEK_START_MONDAY
  FROM hive_metastore.dm_prod.vw_fact_asset_production_forecast_temporal F
  WHERE BUSINESS_DOMAIN_CODE = 'BD0036'
    AND FORECAST_TYPE_CODE = 'IPP'
    AND FORECAST_SCENARIO_NAME = 'Technical'
    AND FORECAST_VERSION_START_DATE >= DATE '2025-01-01'
    AND PRODUCTION_DATETIME >= DATE '2026-01-01'
    AND PRODUCTION_DATETIME >= FORECAST_VERSION_START_DATE
    AND PRODUCTION_DATETIME < add_months(FORECAST_VERSION_START_DATE, 3)
    AND PRODUCTION_DATETIME < current_date()
),
weekly_forecasts AS (
  SELECT
    FH.BUSINESS_AREA_NAME,
    FH.FACILITY_06_SHORT_NAME,
    CONCAT(
      'IPP',
      RIGHT(YEAR(F.FORECAST_VERSION_START_DATE), 2),
      RIGHT(CONCAT(0, MONTH(F.FORECAST_VERSION_START_DATE)), 2)
    ) AS Forecast,
    F.WEEK_START_MONDAY AS `Prod Date`,
    SUM(
      COALESCE(F.PLAN_OIL_PRODUCTION_VOLUME_BBL, 0)
        * COALESCE(F.PLAN_LIQUID_GES_PERCENTAGE, 0) / 100
      + (
          COALESCE(F.PLAN_GAS_PRODUCTION_VOLUME_BEQ, 0)
          - COALESCE(F.PLAN_GAS_FLARE_VOLUME_BEQ, 0)
          - COALESCE(F.PLAN_GAS_FUEL_VOLUME_BEQ, 0)
          - COALESCE(F.PLAN_GAS_VENT_VOLUME_BEQ, 0)
        ) * COALESCE(F.PLAN_GAS_GES_PERCENTAGE, 0) / 100
    ) AS AFS,
    SUM(
      COALESCE(F.PLAN_OIL_SCHEDULED_DEFERRED_VOLUME_BBL, 0)
        * COALESCE(F.PLAN_LIQUID_GES_PERCENTAGE, 0) / 100
      + COALESCE(F.PLAN_GAS_SCHEDULED_DEFERRED_VOLUME_BEQ, 0)
        * COALESCE(F.PLAN_GAS_GES_PERCENTAGE, 0) / 100
    ) AS SCH_DEF,
    SUM(
      COALESCE(F.PLAN_OIL_UNSCHEDULED_DEFERRED_VOLUME_BBL, 0)
        * COALESCE(F.PLAN_LIQUID_GES_PERCENTAGE, 0) / 100
      + COALESCE(F.PLAN_GAS_UNSCHEDULED_DEFERRED_VOLUME_BEQ, 0)
        * COALESCE(F.PLAN_GAS_GES_PERCENTAGE, 0) / 100
    ) AS UNSCH_DEF
  FROM filtered_forecasts AS F
  JOIN hive_metastore.dm_mdm.dim_facility_hierarchy AS FH
    ON FH.FACILITY_ID = F.FACILITY_ID
  WHERE FH.ASSET_DOMAIN_NAME <> 'DW Prod GoM Historic'
  GROUP BY
    FH.BUSINESS_AREA_NAME,
    FH.FACILITY_06_SHORT_NAME,
    CONCAT(
      'IPP',
      RIGHT(YEAR(F.FORECAST_VERSION_START_DATE), 2),
      RIGHT(CONCAT(0, MONTH(F.FORECAST_VERSION_START_DATE)), 2)
    ),
    F.WEEK_START_MONDAY
)
SELECT *
FROM weekly_forecasts
